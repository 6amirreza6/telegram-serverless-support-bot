#!/usr/bin/env node
// ============================================================
// scripts/build-bot-files.js — regenerates docs/bot-files.js
// (the embedded bot source used by the web installer to build
// the deploy zip in the browser).
//
// Run from the repo root:  node scripts/build-bot-files.js
// Re-run after ANY change to the bot source files!
// ============================================================
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const OUT = join(ROOT, 'docs', 'bot-files.js');

// Files included in the generated deploy zip.
const ROOT_FILES = [
  'package.json', 'tgcloud.jsonc', '.gitignore', 'LICENSE',
  'README.md', 'README.fa.md', 'AGENTS.md',
];

const files = {};

for (const f of ROOT_FILES) {
  files[f.split(sep).join('/')] = readFileSync(join(ROOT, f), 'utf8');
}

// every .js under tgcloud/ (schema, lib, handlers)
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) { walk(full); continue; }
    if (!name.endsWith('.js')) continue;
    const key = relative(ROOT, full).split(sep).join('/');
    // safety: never embed a real (git-ignored) seed-config.js
    if (key === 'tgcloud/lib/seed-config.js') continue;
    files[key] = readFileSync(full, 'utf8');
  }
}
walk(join(ROOT, 'tgcloud'));

const banner =
  '// ============================================================\n' +
  '// AUTO-GENERATED by scripts/build-bot-files.js — DO NOT EDIT.\n' +
  '// Embedded copy of the bot source for the web installer\n' +
  '// (docs/index.html) to build the deploy zip in the browser.\n' +
  '// ============================================================\n';

const body = 'window.BOT_FILES = ' + JSON.stringify(files) + ';\n';
writeFileSync(OUT, banner + body, 'utf8');

console.log('bot-files.js written:', Object.keys(files).length, 'files,',
  (body.length / 1024).toFixed(1) + 'KB');
for (const k of Object.keys(files)) console.log('  •', k);
